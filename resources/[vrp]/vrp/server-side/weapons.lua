local function mageWeaponsOrigin()
    return type(vRP.mageAuditOrigin) == "function" and vRP.mageAuditOrigin() or (GetInvokingResource() or GetCurrentResourceName() or "vrp")
end

local function mageWeaponsLog(key, user_id, details)
    if type(vRP.mageAuditLog) == "function" then
        vRP.mageAuditLog(key, {
            actorId = tonumber(user_id),
            actorLabel = "JOGADOR AFETADO",
            details = details
        })
    end
end

local function mageWeaponsSummary(weapons)
    local rows = {}
    for weapon,data in pairs(type(weapons) == "table" and weapons or {}) do
        rows[#rows + 1] = ("%s (%d munições)"):format(tostring(weapon), tonumber(data and data.ammo) or 0)
    end
    table.sort(rows)
    if #rows > 20 then
        local trimmed = {}
        for i = 1,20 do trimmed[#trimmed + 1] = rows[i] end
        trimmed[#trimmed + 1] = ("... e mais %d arma(s)"):format(#rows - 20)
        rows = trimmed
    end
    return table.concat(rows, ", ")
end

function vRP.getWeapons(user_id)
    local data = vRP.user_tables[user_id] or {}
    return data.weapons
end

function vRP.updateAmmo(user_id, weaponsRaw, forcedRemoval)
    local source = vRP.getUserSource(user_id)
    local data = vRP.user_tables[user_id]
    weaponsRaw = type(weaponsRaw) == "table" and weaponsRaw or {}
    forcedRemoval = type(forcedRemoval) == "table" and forcedRemoval or {}
    if data and source then
        local weapons = data.weapons or {}
        for k,v in pairs(weaponsRaw) do
            if weapons[k] then
                if v.ammo > weapons[k].ammo then
                    if GetPlayerRoutingBucket(source) == 0 then
                        mageWeaponsLog("vrp_security_ammo_increase", user_id,
                            ("**Resource:** %s\n**Função:** vRP.updateAmmo\n**Arma:** %s\n**Munição anterior:** %d\n**Munição recebida do client:** %d"):format(
                                mageWeaponsOrigin(), tostring(k), tonumber(weapons[k].ammo) or 0, tonumber(v.ammo) or 0
                            ))
                        Citizen.Trace("\nSpawn de Municao: "..user_id.." - Arma: "..k.." [De "..weapons[k].ammo.." para: "..v.ammo.."]\n")
                        TriggerEvent("AC:ForceBan", vRP.getUserSource(user_id), {
                            reason = "MUNICAO_SPAWN_2",
                            additionalData = k.." ("..weapons[k].ammo.." => "..v.ammo..")",
                            forceBan = false
                        })
                    end
                end
                weapons[k].ammo = v.ammo
            else
                if not forcedRemoval[k] then
                    if GetPlayerRoutingBucket(source) == 0 then
                        mageWeaponsLog("vrp_security_unknown_weapon", user_id,
                            ("**Resource:** %s\n**Função:** vRP.updateAmmo\n**Arma não registrada:** %s\n**Munição informada:** %d"):format(
                                mageWeaponsOrigin(), tostring(k), tonumber(v and v.ammo) or 0
                            ))
                        print("Jogador Suspeito: "..user_id.." - Arma: "..k.." - Removida por não existir na lista de armas do jogador.")
                        TriggerEvent("AC:ForceBan", vRP.getUserSource(user_id), {
                            reason = "WEAPON_SPAWN_12",
                            additionalData = k,
                            forceBan = false
                        })
                    end
                else
                    Citizen.Trace("\nJogador Suspeitasso: "..user_id.." - Arma: "..k.."!\n")
                end
            end
        end
        data.weapons = weapons
        return true
    end
    return false
end

function vRP.addWeapon(user_id, weapon, ammo)
    local data = vRP.user_tables[user_id]
    if data and data.weapons then
        local previous = data.weapons[weapon] and tonumber(data.weapons[weapon].ammo) or nil
        data.weapons[weapon] = { ammo = tonumber(ammo) or 0 }
        mageWeaponsLog("vrp_weapon_added", user_id,
            ("**Resource:** %s\n**Função:** vRP.addWeapon\n**Arma:** %s\n**Munição definida:** %d\n**Munição anterior:** %s"):format(
                mageWeaponsOrigin(), tostring(weapon), tonumber(ammo) or 0, previous ~= nil and tostring(previous) or "arma não existia"
            ))
        return true
    end
    return false
end

function vRP.setWeapons(user_id, weapons)
    local data = vRP.user_tables[user_id]
    if not data or type(weapons) ~= "table" then return false end
    local before = mageWeaponsSummary(data.weapons)
    data.weapons = weapons
    if not next(weapons) then
        local source = vRP.getUserSource(user_id)
        if source then vRPclient._replaceWeapons(source, {}) end
    end
    local after = mageWeaponsSummary(weapons)
    if before ~= after then
        mageWeaponsLog("vrp_weapons_set", user_id,
            ("**Resource:** %s\n**Função:** vRP.setWeapons\n**Antes:** %s\n**Depois:** %s"):format(
                mageWeaponsOrigin(), before ~= "" and before or "Nenhuma", after ~= "" and after or "Nenhuma"
            ))
    end
    return true
end


