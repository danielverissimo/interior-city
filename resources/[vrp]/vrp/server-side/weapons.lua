function vRP.clearWeapons(user_id)
	local source = vRP.getUserSource(user_id)
    local data = vRP.user_tables[user_id]
    if not data then
        return {}
    end

	local old = {}
    if not data.weapons then
        return {}
    end
    local user_weapons = vRPclient.getWeapons(source)
    
    for k,v in pairs(data.weapons) do
        if user_weapons[k] then
            old[k] = v
        end
    end
    for k,v in pairs(user_weapons) do
        if old[k] then
            old[k] = v
        else
            --print("Weapon not found: "..k, user_id)
        end
    end
    
    data.weapons = {}
    if source then vRPclient._replaceWeapons(source, {}) end
    mageWeaponsLog("vrp_weapons_cleared", user_id,
        ("**Resource:** %s\n**Função:** vRP.clearWeapons\n**Armas removidas:** %s"):format(
            mageWeaponsOrigin(), mageWeaponsSummary(old) ~= "" and mageWeaponsSummary(old) or "Nenhuma"
        ))
	return old
end

