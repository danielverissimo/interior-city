local function setPerimeterHidden(hidden)
    for _, object in ipairs(perimeter) do
        if hidden then
            CreateModelHide(object[1], object[2], object[3], 0.75, object[4], true)
        else
            RemoveModelHide(object[1], object[2], object[3], 0.75, object[4], false)
        end
    end
end

