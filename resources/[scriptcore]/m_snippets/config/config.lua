CreateThread(function()
    local json_doors = {}
    for _, door in ipairs(config.doors) do
        local converted_door = {
            coords = {
                x = door.coords.x,
                y = door.coords.y,
                z = door.coords.z
            },
            dist = door.distance,
            hash = door.hash[1],
            lock = true,
            perm = door.perm[1]
        }
        table.insert(json_doors, converted_door)
    end

    SaveResourceFile(GetCurrentResourceName(), 'trancas.json', json.encode(json_doors, { indent = true }), -1)
end)
